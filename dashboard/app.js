function farmSteps(r) {
  const chains = r[4] ? r[4].split(',') : [];
  const chain1 = chains.length > 0 ? chains[0] : 'Ethereum';
  const g = GAS_BY_CHAIN[chain1] || ['$0.50-$2', '$4-$10'];
  const tier = r[5] >= 1e8 ? 0 : r[5] >= 2e7 ? 1 : 2;
  const c = {
    name: r[1], chain1,
    capital: ['$500-$2,000', '$200-$800', '$50-$300'][tier],
    tranche: ['$300-$700', '$100-$300', '$25-$100'][tier],
    gas: g[0], gasWeek: g[1],
  };
  if (r[12] === 1) {
    return [
      `Do not farm ${c.name} for a launch of its own: it is a wrapped, staked or bridged product, or an exchange's own product, so any token value already sits with the parent asset. Cost: $0 - the step is skipping it.`,
      `If you want the exposure, hold or stake the underlying asset through its own protocol instead, where any future distribution would be based. Cost: the parent product's normal gas, about ${c.gas} per transaction on ${c.chain1}.`,
      `Watch the parent protocol's announcements rather than ${c.name}'s: distributions for products like this are paid on the underlying asset, not on the wrapped form. Cost: $0 and about 5 minutes a month.`,
      `Once a month, re-check whether ${c.name} still records no token of its own in the data; if that ever changes, rebuild the plan around the new token's own market. Cost: $0 and 5 minutes monthly.`,
    ];
  }
  const key = playbookKey(R.cats[r[3]]);
  return [
    `Open a fresh wallet used only for ${c.name} and fund it with ${c.capital} of working capital on ${c.chain1}. One wallet, used consistently, is the identity a points program rewards. Setup costs about ${c.gas} in gas and 20 minutes.`,
    CORE_STEP[key](c),
    CADENCE_STEP[key](c),
    `Once a week, open the ${c.name} app and record your points, balance and any season deadline in a tracking sheet, with a screenshot. Launch snapshots are rarely announced in advance. Cost: $0 and about 10 minutes weekly.`,
    `Keep every ${c.name} action on that single wallet: vary amounts by roughly 10-20 percent, spread actions across different days, and never mirror the same amounts from other wallets. Cost: $0; consistency, not volume, is what survives a sybil filter.`,
    `Once a month, check ${c.name}'s governance forum and official announcements for a token vote, a points season end or a claim window, and keep your transaction hashes in the tracking sheet. Cost: $0 and about 15 minutes monthly.`,
  ];
}

/* ---- model factors, recomputed for the detail breakdown ---- */
function clamp(x, lo, hi) { return Math.max(lo, Math.min(hi, x)); }
function momentumFactor(chg) {
  if (chg === null) return 1;
  const c = clamp(chg, -50, 100);
  return c >= 0 ? 1 + 0.003 * c : 1 + 0.006 * c;
}
function ageFactor(days) {
  if (days < 0) return 1;
  return 1 + 0.25 * clamp(days, 0, 1825) / 1825;
}
function sizeFactor(tvl) { return tvl <= 1e9 ? 1 : Math.pow(1e9 / tvl, 0.08); }
function multOf(catIdx) {
  const m = R.mult.find((x) => x[0] === catIdx);
  return m ? m[1] : 1;
}

/* ---- board ---- */
let sortKey = 'rank';
let sortDir = 1;
const KEYIDX = { rank: 2, name: 1, tvl: 5, chg: 6, fdv: 7, p: 8, value: 9 };

function currentFilters() {
  return {
    q: $('q').value.trim().toLowerCase(),
    chain: $('chainSel').value,
    cat: $('catSel').value,
    watch: $('watchOnly').checked,
  };
}
function visibleRows() {
  const f = currentFilters();
  let out = rows.filter((r) => {
    if (f.watch && r[10] !== 1) return false;
    if (f.cat !== '' && R.cats[r[3]] !== f.cat) return false;
    if (f.chain !== '' && !(r[4] ? r[4].split(',') : []).includes(f.chain)) return false;
    if (f.q !== '' && !(r[1].toLowerCase().includes(f.q) || r[0].toLowerCase().includes(f.q))) return false;
    return true;
  });
  const idx = KEYIDX[sortKey];
  out.sort((a, b) => {
    const x = a[idx]; const y = b[idx];
    if (x === null && y === null) return a[2] - b[2];
    if (x === null) return 1;
    if (y === null) return -1;
    const d = typeof x === 'string' ? x.localeCompare(y) : x - y;
    return d * sortDir;
  });
  return out;
}
function renderBoard() {
  const vis = visibleRows();
  $('rowCount').textContent = vis.length + ' of ' + rows.length + ' protocols';
  $('rows').innerHTML = vis.map((r) => {
    const chg = r[6] === null ? '<td class="num">—</td>'
      : '<td class="num ' + (r[6] >= 0 ? 'pos' : 'neg') + '">' + (r[6] >= 0 ? '+' : '') + r[6].toFixed(1) + '%</td>';
    const badge = r[10] === 1 ? '<span class="badge">WATCHLIST</span>' : '';
    const junk = r[12] === 1 ? '<span class="tag-junk">NOT A CANDIDATE</span>' : '';
    return '<tr data-slug="' + esc(r[0]) + '"' + (r[12] === 1 ? ' class="junk"' : '') + '>'
      + '<td class="num">' + r[2] + '</td>'
      + '<td><span class="pname">' + esc(r[1]) + '</span>' + badge + junk + '<br><span class="slug">' + esc(r[0]) + ' · ' + esc(R.cats[r[3]]) + '</span></td>'
      + '<td>' + esc(r[4].split(',').slice(0, 2).join(', ')) + (r[4].split(',').length > 2 ? ' +' + (r[4].split(',').length - 2) : '') + '</td>'
      + '<td class="num">' + fmtUsd(r[5]) + '</td>'
      + chg
      + '<td class="num">' + fmtUsd(r[7]) + '</td>'
      + '<td class="num">' + r[8] + '%</td>'
      + '<td class="num">' + fmtUsd(r[9]) + '</td></tr>';
  }).join('');
}

/* ---- detail ---- */
function renderDetail(slug) {
  const r = bySlug.get(slug);
  if (!r) { location.hash = '#/'; return; }
  const cat = R.cats[r[3]];
  const mult = multOf(r[3]);
  const momF = momentumFactor(r[6]);
  const ageF = ageFactor(r[11]);
  const sizeF = sizeFactor(r[5]);
  const ageTxt = r[11] < 0 ? 'not reported' : r[11] + ' days (' + (r[11] / 365).toFixed(1) + ' years)';
  const steps = farmSteps(r).map((s) => '<li>' + esc(s) + '</li>').join('');
  const chainList = r[4] ? r[4].split(',') : [];
  const chainTxt = chainList.slice(0, 4).join(', ') + (chainList.length > 4 ? ' +' + (chainList.length - 4) + ' more' : '');
  $('detail').innerHTML =
    '<div class="card"><h2>' + esc(r[1])
    + (r[10] === 1 ? '<span class="badge">WATCHLIST</span>' : '')
    + (r[12] === 1 ? '<span class="tag-junk">NOT A CANDIDATE</span>' : '')
    + '</h2><p class="slug">' + esc(r[0]) + ' · ' + esc(cat) + ' · rank #' + r[2] + ' of ' + rows.length + ' · ' + esc(chainTxt) + '</p>'
    + '<div class="grid">'
    + '<div><span>TVL</span><b class="num">' + fmtFull(r[5]) + '</b></div>'
    + '<div><span>7d change</span><b class="num">' + (r[6] === null ? 'not reported' : (r[6] >= 0 ? '+' : '') + r[6].toFixed(1) + '%') + '</b></div>'
    + '<div><span>Tokenless age</span><b>' + ageTxt + '</b></div>'
    + '<div><span>Implied FDV</span><b class="num">' + fmtFull(r[7]) + '</b></div>'
    + '<div><span>Implied value</span><b class="num">' + fmtFull(r[9]) + '</b></div>'
    + '</div>'
    + '<h3>How the model gets there</h3>'
    + '<div class="strip">'
    + '<div><span>Category multiple</span><b class="num">×' + mult.toFixed(3) + '</b></div>'
    + '<div><span>Momentum (7d)</span><b class="num">×' + momF.toFixed(3) + '</b></div>'
    + '<div><span>Age factor</span><b class="num">×' + ageF.toFixed(3) + '</b></div>'
    + '<div><span>Size decay</span><b class="num">×' + sizeF.toFixed(3) + '</b></div>'
    + '<div><span>P(launch)</span><b class="num">' + r[8] + '%</b></div>'
    + '<div><span>Airdrop share</span><b class="num">7.5%</b></div>'
    + '</div>'
    + '<p class="note">Implied FDV = TVL × category multiple (the median mcap/TVL of the category\'s tokenised peers) × momentum × age × size decay. Implied value = implied FDV × 7.5% × P(launch). P(launch) blends the TVL tier, tokenless age, the category tokenisation rate and momentum sign.</p>'
    + '<h3>Farm plan</h3><ol class="steps">' + steps + '</ol>'
    + '</div>';
  $('boardView').hidden = true;
  $('detailView').hidden = false;
  window.scrollTo(0, 0);
}
function showBoard() {
  $('detailView').hidden = true;
  $('boardView').hidden = false;
}

/* ---- routing: #/ board, #/chain=X&watch=1 filtered, #/p/<slug> detail ---- */
function route() {
  const h = location.hash.replace(/^#\/?/, '');
  if (h.startsWith('p/')) { renderDetail(decodeURIComponent(h.slice(2))); return; }
  showBoard();
  $('q').value = '';
  $('chainSel').value = '';
  $('catSel').value = '';
  $('watchOnly').checked = false;
  sortKey = 'rank';
  sortDir = 1;
  if (h) {
    const params = new URLSearchParams(h);
    if (params.get('chain')) $('chainSel').value = params.get('chain');
    if (params.get('cat')) $('catSel').value = params.get('cat');
    if (params.get('watch') === '1') $('watchOnly').checked = true;
    if (params.get('q')) $('q').value = params.get('q');
  }
  renderBoard();
}

/* ---- init ---- */
function init() {
  const watchCount = rows.filter((r) => r[10] === 1).length;
  $('stats').innerHTML =
    '<div><b class="num">' + R.scanned + '</b><span>protocols scanned</span></div>'
    + '<div><b class="num">' + R.preToken + '</b><span>record no token</span></div>'
    + '<div><b class="num">' + watchCount + '</b><span>on the watchlist</span></div>';
  $('asOf').textContent = R.asOf;
  $('globalMult').textContent = '×' + (R.globalMult ? R.globalMult.toFixed(3) : '—');
  const chains = new Set();
  rows.forEach((r) => (r[4] ? r[4].split(',') : []).forEach((c) => chains.add(c)));
  [...chains].sort().forEach((c) => {
    const o = document.createElement('option'); o.value = c; o.textContent = c; $('chainSel').appendChild(o);
  });
  R.cats.forEach((c) => {
    const o = document.createElement('option'); o.value = c; o.textContent = c; $('catSel').appendChild(o);
  });
  $('multRows').innerHTML = R.mult
    .map((m) => [R.cats[m[0]], m[1], m[2], m[3]])
    .sort((a, b) => a[0].localeCompare(b[0]))
    .map((m) => '<tr><td>' + esc(m[0]) + '</td><td class="num">' + m[2] + '</td><td class="num">×' + m[1].toFixed(3) + '</td><td class="num">' + m[3] + '%</td></tr>')
    .join('');
  ['q', 'chainSel', 'catSel', 'watchOnly'].forEach((id) => $(id).addEventListener('input', renderBoard));
  document.querySelectorAll('th.sortable').forEach((th) => {
    th.addEventListener('click', () => {
      const k = th.getAttribute('data-k');
      if (sortKey === k) sortDir *= -1;
      else { sortKey = k; sortDir = k === 'name' ? 1 : -1; if (k === 'rank') sortDir = 1; }
      renderBoard();
    });
  });
  $('rows').addEventListener('click', (ev) => {
    const tr = ev.target.closest('tr[data-slug]');
    if (tr) location.hash = '#/p/' + encodeURIComponent(tr.getAttribute('data-slug'));
  });
  window.addEventListener('hashchange', route);
  route();
}
init();
