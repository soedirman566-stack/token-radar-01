function playbookKey(cat) {
  switch (cat) {
    case 'Lending': case 'Uncollateralized Lending': case 'CDP': case 'CDP Manager': case 'Collateral Markets': return 'lending';
    case 'Dexs': return 'dex';
    case 'Derivatives': case 'Interest Rate Derivatives': case 'Options Vault': return 'perps';
    case 'Yield': case 'Yield Aggregator': case 'Leveraged Farming': case 'Farm': case 'Basis Trading': return 'yield';
    case 'Risk Curators': case 'Onchain Capital Allocator': return 'curator';
    case 'RWA': return 'rwa';
    default: return 'generic';
  }
}
