/* Token Launch Radar — board, filters, detail view.
   Data arrives as window.RADAR from data.js, generated by main.ts.
   Row shape: [slug, name, rank, catIdx, chainsCsv, tvl, chg7d, impliedFdv,
               pLaunchPct, impliedValue, watchlist, ageDays, notCandidate] */
const R = window.RADAR;
const rows = R.rows;
const bySlug = new Map(rows.map((r) => [r[0], r]));
const $ = (id) => document.getElementById(id);

function fmtUsd(n) {
  if (n >= 1e9) return '$' + (n / 1e9).toFixed(2) + 'B';
  if (n >= 1e6) return '$' + (n / 1e6).toFixed(1) + 'M';
  if (n >= 1e3) return '$' + (n / 1e3).toFixed(1) + 'K';
  return '$' + n;
}
function fmtFull(n) { return '$' + n.toLocaleString('en-US'); }
function esc(s) {
  return String(s).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
}

